// Builds lib/trial-page.ts from trial-src/head.html + trial-src/app.js. Run: node scripts/gen-trial-page.js
const fs = require("fs")
const head = fs.readFileSync("trial-src/head.html", "utf8").trimEnd()
const app = fs.readFileSync("trial-src/app.js", "utf8")
const html = head + "\n<script>\n" + app + "\n</script>\n</body></html>\n"
fs.writeFileSync("lib/trial-page.ts", "// GENERATED by scripts/gen-trial-page.js from trial-src/. Do not edit by hand.\nexport const TRIAL_HTML = " + JSON.stringify(html) + "\n")
fs.writeFileSync("/tmp/trial-check.js", app)
console.log("lib/trial-page.ts", html.length)

const admin = fs.readFileSync("trial-src/admin.html", "utf8")
fs.writeFileSync("lib/trial-admin-page.ts", "// GENERATED by scripts/gen-trial-page.js from trial-src/admin.html. Do not edit by hand.\nexport const TRIAL_ADMIN_HTML = " + JSON.stringify(admin) + "\n")
fs.writeFileSync("/tmp/admin-check.js", admin.slice(admin.lastIndexOf("<script>") + 8, admin.lastIndexOf("</script>")))
